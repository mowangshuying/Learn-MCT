/// 新的聚合规则
/// C++17
/// 聚合类型可以有成员函数，只是不能有用户提供的构造函数
/// 聚合类型可以允许以下函数:
    /// 普通成员函数
    /// 运算符重载
    /// 析构函数
    /// 拷贝/移动构造函数 拷贝/移动赋值运算符
    /// 默认成员初始化器 int x = 0; /// c++14

/// 聚合类型不能有这些
    /// 用户提供的构造函数
    /// 私有或者保护的成员
    /// 虚函数
    /// 虚基类
    /// C++20 声明任何构造函数都会让类失去聚合性质


struct Base
{
    int a;
};

struct Derived : Base 
{
    int b;
};

Derived d{{1}, 2};


